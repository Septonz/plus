  verified: BadgeCheck,
  x: X,
  star: Star,
  flower: Flower2,
  medical: Stethoscope,
  person: User,
  bank: Landmark,
  hand: Banknote,
  cash: Banknote,
  globe: Globe,
  wages: Wallet,
  gov: Landmark,
  lock: Lock,
  link: ExternalLink,
  backspace: Delete,
  copy: Copy,
  phone: Smartphone,
  camera: Camera,
  face: ScanFace,
  id: IdCard,
  shield: ShieldCheck,
  sms: MessageSquare,
